#pragma once

#include <QString>
#include <QStringList>
#include <QStringView>

#include <cstdint>
#include <vector>

namespace quarry::ai {

struct DiffHunk
{
    enum class Decision : uint8_t { Pending, Accepted, Rejected };
    qsizetype originalLine = 0; // first line of the original this hunk replaces (0-based)
    QStringList removed; // original lines
    QStringList added; // lines proposed by the AI ("Generated by AI" while Pending)
    bool modifiesData = false; // the added lines contain DML or DDL: flag before running
    Decision decision = Decision::Pending;
};

// A line diff between the script and the AI's working copy. The original never changes here:
// result() applies only the accepted hunks (pending and rejected keep the original lines).
class ScriptDiff
{
public:
    static ScriptDiff compute(QStringView original, QStringView proposed);

    const std::vector<DiffHunk> &hunks() const { return m_hunks; }
    const QString &original() const { return m_original; }
    bool hasPending() const;

    void accept(qsizetype hunk);
    void reject(qsizetype hunk);
    void acceptAll();
    void rejectAll();
    bool canUndo() const { return !m_undo.empty(); }
    bool undo(); // reverts the last accept/reject/acceptAll/rejectAll

    QString result() const;

    static bool modifiesData(const QStringList &lines);

private:
    void decide(qsizetype hunk, DiffHunk::Decision decision, bool record);

    QString m_original;
    QStringList m_originalLines;
    bool m_trailingNewline = false;
    std::vector<DiffHunk> m_hunks;
    std::vector<std::vector<DiffHunk::Decision>> m_undo; // snapshots before each action
};

} // namespace quarry::ai
